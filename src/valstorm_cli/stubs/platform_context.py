# OPEN VALSTORM SDK STUBS
# This file provides IDE type hints for Open Valstorm serverless functions & triggers.
# Do not import this file at runtime on the server — `platform` is injected automatically.

from typing import Any, Callable, Dict, List, Optional, Union


class TokenUser:
    id: str
    email: str
    name: str
    organization_id: str
    role_id: Optional[str]


class RecordContext:
    async def get(self, api_name: str, record_id: str, hydrate: bool = False) -> Optional[Dict[str, Any]]: ...
    async def list(self, api_name: str, limit: int = 50, offset: int = 0, filters: Optional[Dict[str, Any]] = None, hydrate: bool = False) -> List[Dict[str, Any]]: ...
    async def create(self, api_name: str, records: Union[Dict[str, Any], List[Dict[str, Any]]], **kwargs: Any) -> List[Dict[str, Any]]: ...
    async def update(self, api_name: str, records: Union[Dict[str, Any], List[Dict[str, Any]]], **kwargs: Any) -> List[Dict[str, Any]]: ...
    async def delete(self, api_name: str, record_ids: Union[str, List[str]], **kwargs: Any) -> Dict[str, Any]: ...
    async def undelete(self, api_name: str, record_ids: Union[str, List[str]]) -> Dict[str, Any]: ...


class QueryContext:
    async def sql(self, query: str, limit: Optional[int] = None, hydrate: bool = False, bypass_cache: bool = False) -> List[Dict[str, Any]]: ...
    async def graphql(self, query: str, variables: Optional[Dict[str, Any]] = None, operation_name: Optional[str] = None) -> Dict[str, Any]: ...


class SchemaContext:
    async def list(self) -> List[Dict[str, Any]]: ...
    async def get(self, api_name: str) -> Dict[str, Any]: ...
    async def create(self, schema_data: Dict[str, Any]) -> Dict[str, Any]: ...
    async def update(self, api_name: str, schema_data: Dict[str, Any]) -> Dict[str, Any]: ...
    async def delete(self, api_name: str) -> bool: ...
    async def sync_status(self) -> Dict[str, Any]: ...
    async def sync_from_postgres(self, objects: Optional[List[str]] = None, prune_missing_columns: bool = False) -> Dict[str, Any]: ...


class AppContext:
    async def list_installed(self) -> List[Dict[str, Any]]: ...
    async def list_marketplace(self) -> List[Dict[str, Any]]: ...
    async def install(self, app_id: str) -> Dict[str, Any]: ...
    async def uninstall(self, app_id: str, **kwargs: Any) -> Dict[str, Any]: ...
    async def deploy(self, bundle: Dict[str, Any]) -> Dict[str, Any]: ...
    async def promote(self, app_id: str, target_org_id: str) -> Dict[str, Any]: ...
    async def pull_metadata(self, **kwargs: Any) -> Dict[str, Any]: ...
    async def push_metadata(self, payload: Dict[str, Any]) -> Dict[str, Any]: ...


class VfsContext:
    async def tree(self) -> List[Dict[str, Any]]: ...
    async def get_vault(self, vault_id: str) -> Dict[str, Any]: ...
    async def resolve_path(self, path: str) -> Dict[str, Any]: ...
    async def get_file(self, file_id: str) -> Dict[str, Any]: ...
    async def search(self, query: str, limit: int = 10, vault_id: Optional[str] = None) -> Dict[str, Any]: ...
    async def move(self, item_id: str, item_type: str, target_vault_id: Optional[str]) -> Dict[str, Any]: ...
    async def delete(self, item_id: str) -> bool: ...


class FileContext:
    async def get(self, file_id: str) -> Dict[str, Any]: ...
    async def read_text(self, file_id: str) -> str: ...
    async def upload(self, name: str, content: bytes, vault_id: Optional[str] = None, is_public: bool = False) -> Dict[str, Any]: ...
    async def get_versions(self, file_id: str) -> List[Dict[str, Any]]: ...


class FunctionContext:
    async def execute(self, *, function_id: Optional[str] = None, function_name: Optional[str] = None, code: Optional[str] = None, inputs: Optional[Dict[str, Any]] = None, timeout_sec: float = 30.0) -> Any: ...
    async def validate(self, code: str, function_name: str = "test_function", inputs: Optional[Dict[str, Any]] = None, timeout_sec: float = 30.0) -> Dict[str, Any]: ...


class NotificationContext:
    async def send(self, user_ids: List[str], title: str, message: str, **kwargs: Any) -> Dict[str, Any]: ...


class PlatformContext:
    """
    Open Valstorm PlatformContext injected into serverless functions and record/API triggers.
    Active plugins (e.g. ai, github, stripe, quickbooks, twilio) are attached dynamically as attributes.
    """

    user: TokenUser
    org_id: str
    records: RecordContext
    query: QueryContext
    schemas: SchemaContext
    apps: AppContext
    vfs: VfsContext
    files: FileContext
    functions: FunctionContext
    notifications: NotificationContext

    def __getattr__(self, name: str) -> Any: ...
